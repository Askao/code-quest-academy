// Turns src/content/assessments/{ocr,aqa}.json into the seed migration
//   supabase/migrations/20260926130000_seed_assessment_questions.sql
//
//   node scripts/build-assessment-seed.mjs
//
// The questions are authored (and reviewed) as JSON in git; the database only
// ever receives them through this generated SQL. The SQL is safe to apply
// again after the pool grows or a question is corrected: questions are
// upserted by id, and a mark scheme that got shorter has its surplus points
// removed. Marking that has already happened is unaffected - assessment_marks
// keeps its own copy of each point's marks.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(root, "supabase/migrations/20260926130000_seed_assessment_questions.sql");
const boards = ["ocr", "aqa"];

// Dollar-quoting means no character in a question can end the string early
// (the quote-balance bug CLAUDE.md warns about). The tag just has to be one
// that never appears in the content.
const TAG = "$aq$";
const q = (s) => {
  if (String(s).includes(TAG)) throw new Error(`content contains the quote tag ${TAG}`);
  return `${TAG}${s}${TAG}`;
};

const questions = boards.flatMap((b) =>
  JSON.parse(fs.readFileSync(path.join(root, `src/content/assessments/${b}.json`), "utf8")),
);

let sql = `-- GENERATED by scripts/build-assessment-seed.mjs from src/content/assessments/*.json.
-- Do not edit by hand - change the JSON and regenerate. Safe to re-run.
-- ${questions.length} questions.

`;

for (const x of questions) {
  sql += `INSERT INTO public.assessment_questions (id, track, board, topic, marks, ability, answer_format, question)
VALUES (${q(x.id)}, 'gcse', ${q(x.board)}, ${q(x.topic)}, ${x.marks}, ${x.ability}, ${q(x.format)}, ${q(x.question)})
ON CONFLICT (id) DO UPDATE SET board = EXCLUDED.board, topic = EXCLUDED.topic, marks = EXCLUDED.marks,
  ability = EXCLUDED.ability, answer_format = EXCLUDED.answer_format, question = EXCLUDED.question;
DELETE FROM public.assessment_mark_points WHERE question_id = ${q(x.id)} AND position > ${x.markScheme.length};
`;
  x.markScheme.forEach((p, i) => {
    sql += `INSERT INTO public.assessment_mark_points (question_id, position, text, marks, guidance)
VALUES (${q(x.id)}, ${i + 1}, ${q(p.text)}, ${p.marks}, ${q(p.guidance ?? "")})
ON CONFLICT (question_id, position) DO UPDATE SET text = EXCLUDED.text, marks = EXCLUDED.marks, guidance = EXCLUDED.guidance;
`;
  });
  sql += "\n";
}

fs.writeFileSync(OUT, sql);
console.log(`Wrote ${path.relative(root, OUT)} - ${questions.length} questions`);
